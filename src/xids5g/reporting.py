"""Assembly of the reader-facing Results.md and Analysis.md documents.

Each pipeline stage writes a *fragment* describing what it produced. The
fragments belonging to one research objective are then merged, in a fixed
order, into the two documents that live in that objective's Results folder.
Re-running a stage rewrites its fragment and rebuilds the documents, so the
narrative always matches the numbers currently on disk.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any

from . import config as C


def _frag_dir(profile: str) -> Path:
    d = C.ARTIFACTS_DIR / profile / "findings"
    d.mkdir(parents=True, exist_ok=True)
    return d


def write_fragment(profile: str, objective: int, step: str, order: int, *,
                   results_md: str, analysis_md: str,
                   headline: dict[str, Any] | None = None) -> None:
    """Record one stage's contribution to an objective's documentation."""
    payload = {
        "objective": objective,
        "step": step,
        "order": order,
        "results_md": results_md.strip(),
        "analysis_md": analysis_md.strip(),
        "headline": headline or {},
        "generated": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "profile": profile,
    }
    path = _frag_dir(profile) / f"ro{objective}__{order:02d}_{step}.json"
    path.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
    build_objective_docs(profile, objective)


def load_fragments(profile: str, objective: int | None = None) -> list[dict]:
    out = []
    for p in sorted(_frag_dir(profile).glob("ro*__*.json")):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except Exception:
            continue
        if objective is None or d.get("objective") == objective:
            out.append(d)
    return sorted(out, key=lambda d: (d["objective"], d["order"]))


HEADER_NOTE = (
    "> This file is generated by the pipeline. Every number in it was produced "
    "by the run whose timestamp appears above - nothing is transcribed by hand."
)


def _doc_header(objective: int, kind: str, profile: str, generated: str) -> str:
    prof = C.PROFILES.get(profile)
    n = f"{prof.n_rows:,}" if (prof and prof.n_rows) else "1,215,890 (all)"
    return (
        f"# Research Objective {objective} - {kind}\n\n"
        f"**Objective.** {C.RO_TITLES[objective]}\n\n"
        f"| | |\n|---|---|\n"
        f"| Run profile | `{profile}` ({n} flows sampled from 5G-NIDD) |\n"
        f"| Generated | {generated} |\n"
        f"| Dataset | 5G-NIDD `Combined.csv` (1,215,890 flows x 52 columns) |\n"
        f"| Random seed | {C.SEED} (fixed; the run is reproducible) |\n\n"
        f"{HEADER_NOTE}\n\n---\n"
    )


def build_objective_docs(profile: str, objective: int) -> tuple[Path, Path]:
    frags = load_fragments(profile, objective)
    out_dir = C.ro_dir(objective)
    out_dir.mkdir(parents=True, exist_ok=True)
    generated = frags[-1]["generated"] if frags else datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S")

    res = [_doc_header(objective, "Results", profile, generated)]
    ana = [_doc_header(objective, "Analysis", profile, generated)]
    for f in frags:
        if f["results_md"]:
            res.append(f["results_md"] + "\n")
        if f["analysis_md"]:
            ana.append(f["analysis_md"] + "\n")

    if len(frags) == 0:
        res.append("_No stage has been run for this objective yet._\n")
        ana.append("_No stage has been run for this objective yet._\n")

    res_p = out_dir / "Results.md"
    ana_p = out_dir / "Analysis.md"
    res_p.write_text("\n".join(res), encoding="utf-8")
    ana_p.write_text("\n".join(ana), encoding="utf-8")
    return res_p, ana_p


# --------------------------------------------------------------------------
# Small markdown helpers used by the stages
# --------------------------------------------------------------------------
def fig_ref(objective: int, filename: str, caption: str) -> str:
    """Embed a figure with a caption, using a path relative to the .md file."""
    return f"![{caption}](figures/{filename})\n\n*Figure: {caption}*\n"


def file_ref(filename: str, what: str) -> str:
    return f"- [`{filename}`](raw_results/{filename}) - {what}"


def kv_table(pairs: dict[str, Any], key_header: str = "Quantity",
             val_header: str = "Value") -> str:
    lines = [f"| {key_header} | {val_header} |", "|---|---|"]
    for k, v in pairs.items():
        if isinstance(v, float):
            v = f"{v:,.4f}" if abs(v) < 1000 else f"{v:,.2f}"
        elif isinstance(v, int):
            v = f"{v:,}"
        lines.append(f"| {k} | {v} |")
    return "\n".join(lines)
